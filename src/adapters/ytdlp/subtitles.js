/**
 * Extrai legendas do JSON do yt-dlp (chaves subtitles + automatic_captions).
 * Legendas manuais têm prioridade sobre automáticas.
 * P12.1: subtitle track extraction.
 */
export function buildSubtitleTracks(info) {
  const tracks = [];
  const seen = new Set();

  // Manual subtitles
  for (const [lang, entries] of Object.entries(info?.subtitles || {})) {
    const best = entries.find((e) => e.ext === 'vtt') || entries[0];
    if (!best) continue;
    const key = `${lang}:manual`;
    if (seen.has(key)) continue;
    seen.add(key);
    tracks.push({
      language: lang,
      label: best.name || lang,
      isAutoGenerated: false,
      isDefault: false,
      format: { ext: best.ext || 'vtt', url: best.url || '' },
    });
  }

  // Auto-generated subtitles (ASR) — only if no manual version exists
  for (const [lang, entries] of Object.entries(info?.automatic_captions || {})) {
    if (seen.has(`${lang}:manual`)) continue;
    const best = entries.find((e) => e.ext === 'vtt') || entries[0];
    if (!best) continue;
    tracks.push({
      language: lang,
      label: `${lang} (auto)`,
      isAutoGenerated: true,
      isDefault: false,
      format: { ext: best.ext || 'vtt', url: best.url || '' },
    });
  }

  return tracks;
}
